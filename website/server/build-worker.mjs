import { readFile, writeFile } from 'node:fs/promises';
const shared = await readFile(new URL('./quote.mjs', import.meta.url), 'utf8');
const entry = await readFile(new URL('./worker-entry.mjs', import.meta.url), 'utf8');
await writeFile(new URL('./cloudflare-worker.mjs', import.meta.url), '// Generated by node website/server/build-worker.mjs. Contains no API key.\n' + shared.replace('export async function handleQuote', 'async function handleQuote') + '\n' + entry.replace("import { handleQuote } from './quote.mjs';", ''));
console.log('Created website/server/cloudflare-worker.mjs');
